import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from openpyxl import Workbook

OUT = Path(__file__).resolve().parent.parent / "data" / "sample_docs"
OUT.mkdir(parents=True, exist_ok=True)


def _w(filename: str, content: str):
    (OUT / filename).write_text(content, encoding="utf-8")
    print(f"已生成:{filename}")


# ==================== 通用:中文 PDF / Excel / Word 生成 ====================

def _pdf_font():
    """找 Windows 自带中文字体,返回字体名;找不到返回 None。"""
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont
    candidates = [
        ("MSYH", r"C:\Windows\Fonts\msyh.ttc"),
        ("SIMSUN", r"C:\Windows\Fonts\simsun.ttc"),
        ("SIMHEI", r"C:\Windows\Fonts\simhei.ttf"),
    ]
    for name, path in candidates:
        if Path(path).exists():
            try:
                pdfmetrics.registerFont(TTFont(name, path, subfontIndex=0))
                return name
            except Exception:  # noqa: BLE001
                continue
    return None


def _write_pdf(filename: str, title: str, lines: list[str]):
    from reportlab.lib.pagesizes import A4
    from reportlab.pdfgen import canvas
    font = _pdf_font()
    if not font:
        print(f"跳过 {filename}(未找到中文字体)")
        return
    c = canvas.Canvas(str(OUT / filename), pagesize=A4)
    c.setFont(font, 16)
    c.drawString(60, 800, title)
    y = 740
    for text in lines:
        c.setFont(font, 12)
        c.drawString(60, y, text)
        y -= 30
    c.save()
    print(f"已生成:{filename}")


def _write_xlsx(filename: str, sheet: str, header: list[str], rows: list[list]):
    wb = Workbook()
    ws = wb.active
    ws.title = sheet
    ws.append(header)
    for r in rows:
        ws.append(r)
    wb.save(OUT / filename)
    print(f"已生成:{filename}")


def _write_docx(filename: str, title: str, paragraphs: list[tuple[int, str]]):
    """paragraphs: [(级别, 文本), ...],级别 0 为普通段落。"""
    from docx import Document
    doc = Document()
    doc.add_heading(title, level=1)
    for level, text in paragraphs:
        doc.add_heading(text, level=level) if level else doc.add_paragraph(text)
    doc.save(OUT / filename)
    print(f"已生成:{filename}")


