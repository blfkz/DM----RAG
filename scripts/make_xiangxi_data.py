def _w(name: str, content: str):
    """写一份 md/txt 文档。"""
    (OUT_DIR / name).write_text(content, encoding="utf-8")


def _write_pdf(name: str, title: str, paragraphs: list[str]):
    """生成一份中文 PDF 文档(reportlab,黑体)。"""
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont
    from reportlab.platypus import Paragraph, SimpleDocTemplate

    pdfmetrics.registerFont(TTFont("CN", r"C:\Windows\Fonts\simhei.ttf"))
    st_t = ParagraphStyle("t", fontName="CN", fontSize=16, spaceAfter=10)
    st_p = ParagraphStyle("p", fontName="CN", fontSize=10.5, leading=16, spaceAfter=6)
    doc = SimpleDocTemplate(str(OUT_DIR / name), pagesize=A4)
    story = [Paragraph(title, st_t)]
    for para in paragraphs:
        story.append(Paragraph(para.replace("&", "&amp;").replace("<", "&lt;"), st_p))
    doc.build(story)


def _write_xlsx(name: str, sheet_title: str, headers: list[str], rows: list[list]):
    """生成一份 xlsx 表格文档。"""
    from openpyxl import Workbook
    wb = Workbook()
    ws = wb.active
    ws.title = sheet_title
    ws.append(headers)
    for r in rows:
        ws.append(r)
    wb.save(OUT_DIR / name)


def _write_docx(name: str, title: str, sections: list[tuple[str, str]]):
    """生成一份 docx 文档。"""
    from docx import Document
    doc = Document()
    doc.add_heading(title, level=1)
    for h, body in sections:
        doc.add_heading(h, level=2)
        doc.add_paragraph(body)
    doc.save(OUT_DIR / name)


